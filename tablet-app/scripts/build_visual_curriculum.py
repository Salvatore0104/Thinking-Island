def option(label: str, emoji: str) -> dict[str, str]:
    return {"label": label, "emoji": emoji}


def level(
    module: int,
    title: str,
    icon: str,
    skill: str,
    visual: str,
    voice: str,
    choices: list[tuple[str, str]],
    answer: int,
    hint: str,
    explain: str,
) -> dict:
    level_id = len(LEVELS) + 1
    return {
        "id": level_id,
        "week": (level_id - 1) // 6 + 1,
        "title": title,
        "subtitle": f"能力岛 {module}",
        "icon": icon,
        "color": COLORS[(module - 1) % len(COLORS)],
        "skill": skill,
        "activities": [
            {
                "prompt": visual,
                "voicePrompt": voice,
                "instruction": "🔊",
                "visualOnly": True,
                "options": [option(label, emoji) for label, emoji in choices],
                "answer": answer,
                "hint": hint,
                "explain": explain,
            }
        ],
    }


